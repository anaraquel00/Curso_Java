package Revisao_Repeticao;

public class Ex01 {

	public static void main(String[] args) {
		/* Faça um programa que inicia uma 
		 * contagem regressiva a partir de 10 até 1,
		 * imprimindo cada número na tela.
		 * i = interacao
		 */ 
		for(int i = 10; i > 0; i--) {

			System.out.print(i);

			}

	}

}
